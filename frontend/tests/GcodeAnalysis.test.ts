// ── Print time estimation ──

describe('estimatePrintTime', () => {
  it('parses Cura TIME comment', () => {
    const lines = [';TIME:3600', 'G1 X10 Y10 F1500'];
    const est = estimatePrintTime(lines);
    expect(est.estimatedTime).toBe(3600);
    expect(est.method).toBe('comment');
    expect(est.confidence).toBeGreaterThan(0.9);
  });

  it('parses PrusaSlicer estimated printing time', () => {
    const lines = ['; estimated printing time = 1h 30m 0s'];
    const est = estimatePrintTime(lines);
    expect(est.estimatedTime).toBe(5400); // 1h30m = 5400s
    expect(est.method).toBe('comment');
  });

  it('estimates from feed rates when no comment', () => {
    const lines = [
      'G28',
      'G1 X0 Y0 Z0.2 F3600',  // 3600 mm/min = 60 mm/s
      'G1 X100 Y0 E5 F3600',   // 100mm at 60mm/s ≈ 1.67s
    ];
    const est = estimatePrintTime(lines);
    expect(est.estimatedTime).toBeGreaterThan(0);
    expect(est.method).toBe('feedrate');
    expect(est.moveCount).toBeGreaterThan(0);
  });

  it('returns zero for empty input', () => {
    const est = estimatePrintTime([]);
    expect(est.estimatedTime).toBe(0);
  });

  it('returns zero for comment-only input', () => {
    const est = estimatePrintTime(['; comment only']);
    expect(est.estimatedTime).toBe(0);
  });
});

// ── Selection-scoped metrics ──

describe('computeSelectionMetrics', () => {
  it('computes metrics for a range of lines', () => {
    const lines = [
      'G28',
      'G1 X0 Y0 Z0.2 F1500',
      'G1 X100 Y0 E5 F1800',
      'G1 X100 Y100 E10 F1800',
      'G1 X0 Y100 E15 F1800',
    ];
    const metrics = computeSelectionMetrics(lines, 1, 4);
    expect(metrics.startLine).toBe(1);
    expect(metrics.endLine).toBe(4);
    expect(metrics.moveCount).toBe(3);
    expect(metrics.pathLength).toBeCloseTo(300, 0); // 100+100+100
    expect(metrics.extrusionLength).toBeCloseTo(15, 0); // 5+5+5
    expect(metrics.estimatedTime).toBeGreaterThan(0);
    expect(metrics.feedRateRange.min).toBe(1500);
    expect(metrics.feedRateRange.max).toBe(1800);
  });

  it('handles single line selection', () => {
    const lines = ['G1 X10 Y10 F1500'];
    const metrics = computeSelectionMetrics(lines, 0, 0);
    expect(metrics.moveCount).toBe(0); // no previous position
  });

  it('handles empty range', () => {
    const lines = ['G1 X10 Y10 F1500'];
    const metrics = computeSelectionMetrics(lines, 5, 10);
    expect(metrics.moveCount).toBe(0);
  });

  it('handles comments-only lines in range', () => {
    const lines = ['; comment 1', '; comment 2', 'G1 X10 F1500'];
    const metrics = computeSelectionMetrics(lines, 0, 2);
    expect(metrics.moveCount).toBe(0); // comments skipped
  });

  it('handles empty input', () => {
    const metrics = computeSelectionMetrics([], 0, 10);
    expect(metrics.moveCount).toBe(0);
  });

  it('clamps selection to valid range', () => {
    const lines = ['G1 X10 F1500'];
    const metrics = computeSelectionMetrics(lines, -5, 100);
    expect(metrics.startLine).toBe(0);
    expect(metrics.endLine).toBe(0);
  });
});
