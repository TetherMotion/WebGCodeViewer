// ── Stringing risk detection ──

describe('detectStringingRisk', () => {
  it('detects long travel moves', () => {
    const lines = [
      'G1 X0 Y0 E0 F1500',
      'G0 X100 Y0',  // 100mm travel
      'G1 X100 Y10 E5 F1800',
    ];
    const risks = detectStringingRisk(lines, 20);
    expect(risks.length).toBe(1);
    expect(risks[0].travelDistance).toBeCloseTo(100, 1);
    expect(risks[0].riskScore).toBeGreaterThan(0.5);
  });

  it('ignores short travels', () => {
    const lines = [
      'G1 X0 Y0 E0 F1500',
      'G0 X5 Y0',  // 5mm travel — below threshold
      'G1 X5 Y10 E5 F1800',
    ];
    const risks = detectStringingRisk(lines, 20);
    expect(risks.length).toBe(0);
  });

  it('reduces risk score with retraction', () => {
    const lines = [
      'G1 X0 Y0 E10 F1500',
      'G1 X0 Y0 E5 F1800',  // retraction (E decreases)
      'G0 X100 Y0',          // travel with retraction
      'G1 X100 Y10 E10 F1800', // de-retract
    ];
    const risks = detectStringingRisk(lines, 20, true);
    expect(risks.length).toBe(1);
    expect(risks[0].riskScore).toBeLessThan(0.5); // reduced by retraction
  });

  it('reduces risk for pure Z moves', () => {
    const lines = [
      'G1 X50 Y50 E10 F1500',
      'G0 X50 Y50 Z50',  // pure Z move
      'G1 X50 Y50 Z0.2 E15 F1800',
    ];
    const risks = detectStringingRisk(lines, 20);
    expect(risks.length).toBe(1);
    expect(risks[0].riskScore).toBeLessThan(0.2);
  });

  it('handles empty input', () => {
    expect(detectStringingRisk([])).toEqual([]);
  });

  it('handles comments-only lines', () => {
    const lines = ['; comment 1', '; comment 2'];
    expect(detectStringingRisk(lines)).toEqual([]);
  });
});

// ── Volumetric flow rate ──

describe('computeVolumetricFlow', () => {
  it('computes flow rate for extruding moves', () => {
    const lines = [
      'G1 X0 Y0 E0 F1800',  // 1800 mm/min = 30 mm/s
      'G1 X10 Y0 E5 F1800', // extruding move
    ];
    const samples = computeVolumetricFlow(lines, 0.4, 0.2);
    expect(samples.length).toBeGreaterThan(0);
    // Flow = 0.4 * 0.2 * 30 = 2.4 mm³/s
    expect(samples[0].flowRate).toBeCloseTo(2.4, 1);
  });

  it('skips non-extruding moves', () => {
    const lines = [
      'G1 X0 Y0 E0 F1800',
      'G0 X10 Y0',          // rapid move, no E
      'G1 X10 Y10 F1800',   // G1 without E
    ];
    const samples = computeVolumetricFlow(lines);
    expect(samples.length).toBe(0);
  });

  it('skips retractions (negative E delta)', () => {
    const lines = [
      'G1 X0 Y0 E10 F1800',
      'G1 X0 Y0 E5 F1800',  // retraction (E decreases)
      'G1 X10 Y0 E4 F1800', // still negative delta from 5 to 4 — skip
    ];
    const samples = computeVolumetricFlow(lines);
    // Only the first move (E: 0→10) is extruding; the rest are retractions
    expect(samples.length).toBe(1);
  });

  it('parses layer height from comments', () => {
    const lines = [
      ';LAYER_HEIGHT:0.3',
      'G1 X0 Y0 E0 F1200',
      'G1 X10 Y0 E3 F1200',
    ];
    const samples = computeVolumetricFlow(lines, 0.4, 0.2);
    expect(samples.length).toBeGreaterThan(0);
    expect(samples[0].layerHeight).toBeCloseTo(0.3, 2);
  });

  it('parses extrusion width from comments', () => {
    const lines = [
      ';EXTRUSION_WIDTH:0.6',
      'G1 X0 Y0 E0 F1200',
      'G1 X10 Y0 E3 F1200',
    ];
    const samples = computeVolumetricFlow(lines, 0.4, 0.2);
    expect(samples.length).toBeGreaterThan(0);
    expect(samples[0].extrusionWidth).toBeCloseTo(0.6, 2);
  });

  it('estimates layer height from Z changes', () => {
    const lines = [
      'G1 X0 Y0 Z0.2 E0 F1200',
      'G1 X10 Y0 E3 F1200',
      'G1 X0 Y0 Z0.4 E3 F1200',
      'G1 X10 Y0 E6 F1200',
    ];
    const samples = computeVolumetricFlow(lines, 0.4, 0.2);
    expect(samples.length).toBeGreaterThan(0);
    // After Z change from 0.2 to 0.4, layer height should be ~0.2
    const lastSample = samples[samples.length - 1];
    expect(lastSample.layerHeight).toBeCloseTo(0.2, 2);
  });

  it('handles empty input', () => {
    expect(computeVolumetricFlow([])).toEqual([]);
  });
});

describe('getFlowStats', () => {
  it('computes statistics for flow samples', () => {
    const samples = [
      { lineNumber: 0, flowRate: 1.0, feedRate: 10, extrusionWidth: 0.4, layerHeight: 0.2 },
      { lineNumber: 1, flowRate: 2.0, feedRate: 20, extrusionWidth: 0.4, layerHeight: 0.2 },
      { lineNumber: 2, flowRate: 3.0, feedRate: 30, extrusionWidth: 0.4, layerHeight: 0.2 },
    ];
    const stats = getFlowStats(samples);
    expect(stats.minFlow).toBe(1.0);
    expect(stats.maxFlow).toBe(3.0);
    expect(stats.meanFlow).toBeCloseTo(2.0, 2);
    expect(stats.peakLine).toBe(2);
  });

  it('computes standard deviation', () => {
    const samples = [
      { lineNumber: 0, flowRate: 2.0, feedRate: 10, extrusionWidth: 0.4, layerHeight: 0.2 },
      { lineNumber: 1, flowRate: 4.0, feedRate: 20, extrusionWidth: 0.4, layerHeight: 0.2 },
    ];
    const stats = getFlowStats(samples);
    expect(stats.stdDev).toBeCloseTo(1.0, 2);
  });

  it('returns zeros for empty input', () => {
    const stats = getFlowStats([]);
    expect(stats.minFlow).toBe(0);
    expect(stats.maxFlow).toBe(0);
    expect(stats.peakLine).toBe(-1);
  });
});

// ── Layer time warnings ──

describe('detectLayerTimeWarnings', () => {
  it('detects slow layers', () => {
    const layerTimes = [
      { layerIndex: 0, zHeight: 0.2, timeSeconds: 30 },
      { layerIndex: 1, zHeight: 0.4, timeSeconds: 30 },
      { layerIndex: 2, zHeight: 0.6, timeSeconds: 30 },
      { layerIndex: 3, zHeight: 0.8, timeSeconds: 120 }, // 4x average
    ];
    const warnings = detectLayerTimeWarnings(layerTimes, 2.0, 10);
    const slow = warnings.filter(w => w.warning === 'slow');
    expect(slow.length).toBe(1);
    expect(slow[0].layerIndex).toBe(3);
  });

  it('detects fast layers', () => {
    const layerTimes = [
      { layerIndex: 0, zHeight: 0.2, timeSeconds: 30 },
      { layerIndex: 1, zHeight: 0.4, timeSeconds: 5 }, // too fast
    ];
    const warnings = detectLayerTimeWarnings(layerTimes, 2.0, 10);
    const fast = warnings.filter(w => w.warning === 'fast');
    expect(fast.length).toBe(1);
    expect(fast[0].layerIndex).toBe(1);
  });

  it('skips first layer', () => {
    const layerTimes = [
      { layerIndex: 0, zHeight: 0.2, timeSeconds: 600 }, // very slow but first layer
    ];
    const warnings = detectLayerTimeWarnings(layerTimes, 2.0, 10);
    expect(warnings.length).toBe(0);
  });

  it('handles empty input', () => {
    expect(detectLayerTimeWarnings([])).toEqual([]);
  });
});

// ── G-code error detection ──

describe('detectGcodeErrors', () => {
  it('warns about moves before homing', () => {
    const lines = [
      'G1 X10 Y10 F1500', // move before G28
      'G28',
    ];
    const issues = detectGcodeErrors(lines);
    const homing = issues.filter(i => i.category === 'homing');
    expect(homing.length).toBe(1);
    expect(homing[0].severity).toBe('warning');
  });

  it('warns about G1 without feed rate', () => {
    const lines = [
      'G28',
      'G1 X10 Y10', // no F word
    ];
    const issues = detectGcodeErrors(lines);
    const feedrate = issues.filter(i => i.category === 'feedrate');
    expect(feedrate.length).toBeGreaterThanOrEqual(1);
  });

  it('warns about rapid moves with extrusion', () => {
    const lines = [
      'G28',
      'G1 X0 Y0 E0 F1500',
      'G1 X10 Y10 E5 F1500',
      'G0 X20 Y10 E10', // G0 with E increasing (extrusion during rapid)
    ];
    const issues = detectGcodeErrors(lines);
    const rapid = issues.filter(i => i.category === 'rapid-extrusion');
    expect(rapid.length).toBe(1);
  });

  it('warns about extrusion before temperature', () => {
    const lines = [
      'G28',
      'G1 X10 Y10 E5 F1500', // extruding without temp
    ];
    const issues = detectGcodeErrors(lines);
    const temp = issues.filter(i => i.category === 'temperature');
    expect(temp.length).toBe(1);
  });

  it('warns about excessive feed rate', () => {
    const lines = [
      'G28',
      'G1 X10 Y10 F20000', // very high feed rate
    ];
    const issues = detectGcodeErrors(lines);
    const feedrate = issues.filter(i => i.category === 'feedrate' && i.message.includes('high'));
    expect(feedrate.length).toBe(1);
  });

  it('errors on arc without radius or endpoint', () => {
    const lines = ['G2']; // arc with nothing
    const issues = detectGcodeErrors(lines);
    const arc = issues.filter(i => i.category === 'arc');
    expect(arc.length).toBe(1);
    expect(arc[0].severity).toBe('error');
  });

  it('errors on zero radius arc', () => {
    const lines = ['G2 X10 Y10 R0'];
    const issues = detectGcodeErrors(lines);
    const arc = issues.filter(i => i.category === 'arc' && i.message.includes('zero'));
    expect(arc.length).toBe(1);
    expect(arc[0].severity).toBe('error');
  });

  it('warns about duplicate words', () => {
    const lines = ['G1 X10 X20 Y10 F1500']; // duplicate X
    const issues = detectGcodeErrors(lines);
    const dup = issues.filter(i => i.category === 'duplicate-word');
    expect(dup.length).toBe(1);
  });

  it('returns no issues for clean G-code', () => {
    const lines = [
      'G28',
      'M104 S200',
      'M109 S200',
      'G1 X10 Y10 Z0.2 F1500',
      'G1 X100 Y10 E5 F1800',
    ];
    const issues = detectGcodeErrors(lines);
    expect(issues.length).toBe(0);
  });

  it('handles empty input', () => {
    expect(detectGcodeErrors([])).toEqual([]);
  });
});

